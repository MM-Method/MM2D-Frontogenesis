    ! Evaluates the spline (Pure, mathematical, and instant)
    pure function tanh_spline(val) result(res)
        real(kind=wp), intent(in) :: val
        real(kind=wp)             :: res
        
        integer :: klo, khi, k
        real(kind=wp) :: h, a, b
        
        ! Extrapolation bounds
        if (val <= -5.0_wp) then
            res = -1.0_wp
            return
        else if (val >= 5.0_wp) then
            res = 1.0_wp
            return
        end if
        
        ! Binary search to locate interval
        klo = 1
        khi = N
        do while (khi - klo > 1)
            k = (khi + klo) / 2
            if (x(k) > val) then
                khi = k
            else
                klo = k
            end if
        end do
        
        ! Spline interpolation
        h = x(khi) - x(klo)
        a = (x(khi) - val) / h
        b = (val - x(klo)) / h
        
        res = a * y(klo) + b * y(khi) + &
              ((a**3 - a) * y2(klo) + (b**3 - b) * y2(khi)) * (h**2) / 6.0_wp
              
    end function tanh_spline

